export const copy: Record<Locale, Copy> = { en, fr, es };

export function explain(locale: Locale, caught: unknown, fallback: ErrorCodeName): string {
  const raw = caught instanceof Error && caught.message ? caught.message : fallback;
  const table = copy[locale].errors;
  if (raw in table) return table[raw as ErrorCodeName];
  return table[fallback];
}
